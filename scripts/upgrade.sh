#!/usr/bin/env bash
# =============================================================================
#  IT 运维工单台账与日报系统 —— 安全升级脚本
#  -----------------------------------------------------------------------------
#  作用：拉取最新代码 → 重建容器 → 保留全部数据
#  原则：**绝不带 -v**，不删除数据卷；数据库初始化脚本只在数据卷为空时执行一次，
#        升级、重启、重建容器都不会重新初始化，也不会清掉工单明细。
#
#  用法：
#      bash scripts/upgrade.sh            # 原地升级
#      bash scripts/upgrade.sh --pull     # 先 git pull 再升级
#
#  什么时候才会重新初始化数据库？只有一个情况：
#      手动执行了 docker compose down -v（或手动 docker volume rm）
#  那是删库操作，执行前请先在「系统设置 → 数据管理」下载备份包。
# =============================================================================
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"
COMPOSE="docker compose"

say() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[注意]\033[0m %s\n' "$*"; }

say "升级目录：$ROOT"

if [ ! -f "$ROOT/docker-compose.yml" ]; then
  echo "找不到 docker-compose.yml，请在项目根目录执行：bash scripts/upgrade.sh" >&2
  exit 1
fi

if [ "${1:-}" = "--pull" ]; then
  if [ -d "$ROOT/.git" ]; then
    say "拉取最新代码（保留本地 .env）"
    git pull --ff-only || warn "git pull 失败，跳过，继续用当前代码升级"
  else
    warn "当前目录不是 git 仓库，跳过 pull"
  fi
fi

# ---------------------------------------------------------------------------
# 1. 升级前自检：数据卷是否存在（存在 = 已有数据，不会被重新初始化）
# ---------------------------------------------------------------------------
if docker volume ls --format '{{.Name}}' | grep -q 'mariadb_data'; then
  say "检测到已有数据库卷，本次升级会保留全部工单与账号数据"
else
  warn "没有检测到数据库卷：本次启动会按 sql/init.sql 做**首次初始化**（空库）"
fi

# ---------------------------------------------------------------------------
# 2. 备份提示（不会自动删除任何东西）
# ---------------------------------------------------------------------------
say "建议：升级前登录系统 →「系统设置 → 数据管理」点一次「立即备份」"
say "      备份包在 backend/backups/ 目录，可随时下载回本地"

# ---------------------------------------------------------------------------
# 3. 重建容器（注意：没有 -v，不会动数据卷）
# ---------------------------------------------------------------------------
say "重建并启动容器（保留数据卷）"
$COMPOSE up -d --build

say "等待服务就绪…"
sleep 5
$COMPOSE ps

# ---------------------------------------------------------------------------
# 4. 结果确认
# ---------------------------------------------------------------------------
BACKEND_IP="$(docker inspect -f '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' \
  "$($COMPOSE ps -q backend 2>/dev/null | head -1)" 2>/dev/null || true)"
if [ -n "$BACKEND_IP" ]; then
  say "后端日志（看是否出现「数据库连接成功」）"
  $COMPOSE logs --tail=20 backend || true
fi

echo
say "升级完成。管理端口与管理地址见 .env 的 ADMIN_PORT / PUBLIC_PORT"
warn "不要执行 docker compose down -v —— 那会删除数据库数据卷"
